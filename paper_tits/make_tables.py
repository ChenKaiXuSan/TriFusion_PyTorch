#!/usr/bin/env python3
"""Generate the experiment tables of main.tex (tables/tab_*.tex) from the result files.

Every number comes straight from TriPoseFusion/eval/logs/learned_fusion_experiments (errors in mm)
and, for the downstream table, from the head-movement analysis folder; nothing is typed by hand.
A missing run aborts with the name of the configuration, so a stale table cannot be produced.

    python paper_tits/make_tables.py            # needs numpy only
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent / "TriPoseFusion" / "eval" / "logs" / "learned_fusion_experiments"
HEAD = Path("/work/1/SKIING/chenkaixu/data/drive/downstream_analysis/head_movement_analysis")
OUT = HERE / "tables"
MM = 1000.0
VIEWS = ("front", "left", "right")
GROUPS = ("head", "shoulders_neck", "body", "hands")
ENVS = ("昼多い", "昼少ない", "夜多い", "夜少ない")
METHOD = r"\textbf{\method{}}"


def folds(tag: str, name: str = "result.json", n: int = 5) -> list[dict]:
    out = [json.loads(p.read_text()) for p in sorted((ROOT / tag).glob(f"fold[0-9]/{name}"))]
    if len(out) != n:
        sys.exit(f"!! {tag}/{name}: {len(out)} of {n} folds present")
    return out


def params(n: int) -> str:
    if n == 0:
        return "--"
    return f"{n / 1e6:.2f}M" if n >= 1e6 else f"{n / 1e3:.1f}K" if n < 1e5 else f"{n / 1e3:.0f}K"


def bold(vals: list[float], fmt: str, lowest: bool = True) -> list[str]:
    best = min(vals) if lowest else max(vals)
    return [(r"\best{" + format(v, fmt) + "}") if abs(v - best) < 1e-9 else format(v, fmt) for v in vals]


def write(name: str, lines: list[str]) -> None:
    OUT.mkdir(exist_ok=True)
    (OUT / f"{name}.tex").write_text("% generated by make_tables.py -- do not edit\n" + "\n".join(lines) + "\n")
    print(f"wrote tables/{name}.tex ({len(lines)} lines)")


# ---------------------------------------------------------------- main table
def tab_main() -> None:
    ref = folds("eqb_setfusion")
    base = np.mean([r["training_free"]["fuse_mean"]["mpjpe_m"] for r in ref])

    def stats(rows):
        m = [MM * r["mpjpe_m"] for r in rows]
        p = [MM * r["pa_mpjpe_m"] for r in rows]
        return np.mean(m), np.std(m), np.mean(p), np.std(p), np.mean([r["pck"]["0.10"] for r in rows])

    free = [("Front only", "single_front"), ("Left only", "single_left"), ("Right only", "single_right"),
            ("Best single (oracle)", "best_single_oracle"), ("Median fusion", "fuse_median"), ("Mean fusion", "fuse_mean")]
    free2 = [("Geometric median", "tf_geomedian"), ("Leave-one-out consensus", "tf_consensus"),
             ("Mean + temporal smooth.", "tf_smooth"), ("Procrustes re-alignment", "tf_gpa")]
    learned = [("Convex view weighting", "gating_nt"), ("Concat-MLP", "concat_mlp"), ("Skeleton-Transformer", "skel_tr"),
               ("v1 design retrained", "tripose64"), ("Lifting-MLP", "lift_mlp"), ("Temporal-CNN", "tcn"),
               ("Residual-only", "resid64"), (METHOD, "setfusion")]
    rows = []
    for label, key in free:
        rows.append((label, 0, *stats([r["training_free"][key] for r in ref]), "free"))
    for label, tag in free2:
        rows.append((label, 0, *stats([r["learned_last"] for r in folds(f"eqb_{tag}")]), "free"))
    for label, tag in learned:
        rs = folds(f"eqb_{tag}")
        rows.append((label, rs[0]["params"], *stats([r["learned_last"] for r in rs]), "learned"))
    lr = [r for r in rows if r[-1] == "learned"]
    bm, bp, bk = bold([r[2] for r in lr], ".1f"), bold([r[4] for r in lr], ".1f"), bold([r[6] for r in lr], ".3f", lowest=False)
    lines, i = [], 0
    for r in rows:
        label, n, m, sm, p, sp, k, kind = r
        d = "--" if label == "Mean fusion" else f"${100 * (m / (MM * base) - 1):+.1f}\\%$"
        if kind == "learned":
            if i == 0:
                lines.append(r"\midrule")
            mm_, pp_, kk_ = bm[i], bp[i], bk[i]
            i += 1
        else:
            mm_, pp_, kk_ = f"{m:.1f}", f"{p:.1f}", f"{k:.3f}"
        lines.append(f"{label} & {params(n)} & {mm_}$\\,{{\\pm}}\\,${sm:.1f} & {pp_}$\\,{{\\pm}}\\,${sp:.1f} & {kk_} & {d} \\\\")
    write("tab_main", lines)


# ---------------------------------------------------------------- joint groups / illumination
def per_env(tag: str) -> dict:
    d = {}
    for r in folds(tag):
        for s in r["per_sequence_learned"]:
            d.setdefault(s["env"], []).append((s["metrics"]["mpjpe_m"], s["metrics"]["pa_mpjpe_m"]))
    assert all(len(d[e]) == 22 for e in ENVS), {e: len(v) for e, v in d.items()}
    return {e: MM * np.mean(d[e], axis=0) for e in ENVS}


def tab_groups() -> None:
    ref = folds("eqb_setfusion")
    g = lambda rows: [MM * np.mean([r["groups"][x] for r in rows]) for x in GROUPS]
    data = [("Mean fusion", g([r["training_free"]["fuse_mean"] for r in ref])),
            ("Best single (oracle)", g([r["training_free"]["best_single_oracle"] for r in ref])),
            ("Lifting-MLP", g([r["learned_last"] for r in folds("eqb_lift_mlp")])),
            ("Temporal-CNN", g([r["learned_last"] for r in folds("eqb_tcn")])),
            (r"\method{}", g([r["learned_last"] for r in ref]))]
    cols = [bold([d[1][j] for d in data], ".1f") for j in range(4)]
    lines = [r"\multicolumn{5}{c}{\emph{By joint group (MPJPE)}}\\", r"Method & Head & Shoulders/neck & Non-hand & Hands \\", r"\midrule"]
    for i, (label, _) in enumerate(data):
        lines.append(f"{label} & " + " & ".join(cols[j][i] for j in range(4)) + r" \\")
    mean, tcn, ours = per_env("eqb_mean"), per_env("eqb_tcn"), per_env("eqb_setfusion")
    cell = lambda d, e: f"{d[e][0]:.1f}/{d[e][1]:.1f}"
    lines += [r"\midrule", r"\multicolumn{5}{c}{\emph{By driving condition (MPJPE / PA-MPJPE)}}\\",
              r" & Day/busy & Day/quiet & Night/busy & Night/quiet \\", r"\midrule",
              "Mean fusion & " + " & ".join(cell(mean, e) for e in ENVS) + r" \\",
              "Temporal-CNN & " + " & ".join(cell(tcn, e) for e in ENVS) + r" \\",
              r"\method{} & " + " & ".join(cell(ours, e) for e in ENVS) + r" \\",
              r"$\Delta$MPJPE vs.\ mean & " + " & ".join(f"${100 * (ours[e][0] / mean[e][0] - 1):+.0f}\\%$" for e in ENVS) + r" \\"]
    write("tab_groups", lines)


# ---------------------------------------------------------------- robustness
def stress(tag: str, mode: str, weights: bool):
    fs = folds(tag, f"stress_{mode}.json")
    err = MM * np.mean([np.mean([f[v]["learned"]["mpjpe_m"] for v in VIEWS]) for f in fs])
    w = np.mean([np.mean([f[v]["weight_on_corrupted_view"] for v in VIEWS]) for f in fs]) if weights else None
    ref = MM * np.mean([np.mean([f[v]["fuse_mean_same_corruption"]["mpjpe_m"] for v in VIEWS]) for f in fs])
    orc = MM * np.mean([np.mean([f[v]["fuse_mean_excluding_view_oracle"]["mpjpe_m"] for v in VIEWS]) for f in fs])
    return err, w, ref, orc


def tab_stress() -> None:
    rows = [("Geometric median", "tf_geomedian", True), ("Convex view weighting", "gating_nt", True),
            ("Concat-MLP", "concat_mlp", False), ("Skeleton-Transformer", "skel_tr", False), ("v1 backbone retrained", "tripose64", True),
            ("Lifting-MLP", "lift_mlp", False), ("Temporal-CNN", "tcn", False), ("Residual-only", "resid64", True),
            (r"\method{} w/o aug.", "setfusion_noaug", True), (METHOD, "setfusion", True)]
    ref = {m: stress("eqb_setfusion", m, True) for m in ("drop", "zero", "noise")}
    clean0 = MM * np.mean([r["training_free"]["fuse_mean"]["mpjpe_m"] for r in folds("eqb_setfusion")])
    lines = [f"Mean fusion & {clean0:.1f} & {ref['drop'][2]:.1f} & {ref['zero'][2]:.1f} (0.33) & {ref['noise'][2]:.1f} (0.33) \\\\",
             f"Oracle excl.\\ view & -- & {ref['drop'][3]:.1f} & {ref['zero'][3]:.1f} (0) & {ref['noise'][3]:.1f} (0) \\\\", r"\midrule"]
    data = []
    for label, tag, w in rows:
        clean = MM * np.mean([r["learned_last"]["mpjpe_m"] for r in folds(f"eqb_{tag}")])
        data.append((label, clean, *[stress(f"eqb_{tag}", m, w) for m in ("drop", "zero", "noise")]))
    b = [bold([d[1] for d in data], ".1f")] + [bold([d[k][0] for d in data], ".1f") for k in (2, 3, 4)]
    for i, (label, clean, dr, ze, no) in enumerate(data):
        wz = f" ({ze[1]:.2f})" if ze[1] is not None else ""
        wn = f" ({no[1]:.2f})" if no[1] is not None else ""
        lines.append(f"{label} & {b[0][i]} & {b[1][i]} & {b[2][i]}{wz} & {b[3][i]}{wn} \\\\")
    write("tab_stress", lines)


# ---------------------------------------------------------------- Drive&Act
def tab_da() -> None:
    anchor = folds("daeq_setfusion", n=3)
    tf = lambda key: (MM * np.mean([r["training_free"][key]["mpjpe_m"] for r in anchor]), MM * np.mean([r["training_free"][key]["pa_mpjpe_m"] for r in anchor]))
    sref = [json.loads(p.read_text()) for p in sorted((ROOT / "daeq_setfusion").glob("fold[0-9]/stress_noise.json"))]
    noise_mean = MM * np.mean([np.mean([f[v]["fuse_mean_same_corruption"]["mpjpe_m"] for v in VIEWS]) for f in sref])
    noise_orc = MM * np.mean([np.mean([f[v]["fuse_mean_excluding_view_oracle"]["mpjpe_m"] for v in VIEWS]) for f in sref])
    pair = lambda x: f"{x[0]:.1f}/{x[1]:.1f}"
    lines = [f"Best single view (right) & {pair(tf('single_right'))} & -- & -- & -- \\\\",
             f"Median fusion & {pair(tf('fuse_median'))} & -- & -- & -- \\\\",
             f"Mean fusion & {pair(tf('fuse_mean'))} & -- & -- & {noise_mean:.1f} \\\\",
             f"Oracle excl.\\ view & -- & -- & -- & {noise_orc:.1f} \\\\", r"\midrule"]
    rows = [("Convex view weighting", "gating_nt"), ("Concat-MLP", "concat_mlp"), ("Skeleton-Transformer", "skel_tr"),
            ("v1 design retrained", "tripose64"), ("Lifting-MLP", "lift_mlp"), ("Temporal-CNN", "tcn"), ("Residual-only", "resid64"),
            (METHOD, "setfusion")]
    data = []
    for label, tag in rows:
        zs = folds(f"eqb_{tag}", "crosseval_driveandact.json")
        z = (MM * np.mean([x["learned_mean"]["mpjpe_m"] for x in zs]), MM * np.mean([x["learned_mean"]["pa_mpjpe_m"] for x in zs]))
        res = lambda pre: (lambda rs: (MM * np.mean([r["learned_last"]["mpjpe_m"] for r in rs]), MM * np.mean([r["learned_last"]["pa_mpjpe_m"] for r in rs])))(folds(f"{pre}_{tag}", n=3))
        st = [json.loads(p.read_text()) for p in sorted((ROOT / f"daeq_{tag}").glob("fold[0-9]/stress_noise.json"))]
        assert len(st) == 3, tag
        nz = MM * np.mean([np.mean([f[v]["learned"]["mpjpe_m"] for v in VIEWS]) for f in st])
        data.append((label, z, res("daeqsc"), res("daeq"), nz))  # rig ref. = self-calibrated extrinsics (daeqlf: official)
    bz = bold([d[1][1] for d in data], ".1f")
    bl, bd, bn = bold([d[2][1] for d in data], ".1f"), bold([d[3][1] for d in data], ".1f"), bold([d[4] for d in data], ".1f")
    for i, (label, z, lf, ds, nz) in enumerate(data):
        lines.append(f"{label} & {z[0]:.1f}/{bz[i]} & {lf[0]:.1f}/{bl[i]} & {ds[0]:.1f}/{bd[i]} & {bn[i]} \\\\")
    write("tab_da", lines)


# ---------------------------------------------------------------- downstream
def tab_downstream() -> None:
    sys.path.insert(0, str(HERE.parent / "analysis" / "head_movement"))
    from source_validity import compute
    label = {"view_front": "Front only", "view_left": "Left only", "view_right": "Right only", "fused_median": "Median fusion",
             "fused_mean": "Mean fusion", "fused_main": METHOD}
    data = compute(HEAD)
    assert [d["source"] for d in data] == list(label) and all(d["drives"] == 88 for d in data), data
    br = bold([d["r_mean"] for d in data], ".2f", lowest=False)
    bmin = bold([d["r_min"] for d in data], ".2f", lowest=False)
    ba = bold([abs(d["amplitude"] - 1) for d in data], ".2f")
    lines = []
    for i, d in enumerate(data):
        amp = f"{d['amplitude']:.2f}"
        if ba[i].startswith(r"\best"):
            amp = r"\best{" + amp + "}"
        lines.append(f"{label[d['source']]} & {br[i]} & {bmin[i]} & {d['failed']} & {amp} & {100 * d['glance']:.1f} & {d['turns_per_min']:.2f} \\\\")
    write("tab_downstream", lines)


# ---------------------------------------------------------------- ablations, budget, window
def tab_ablation() -> None:
    rows = [(r"\method{} (full)", "setfusion"), (r"\;-- corruption aug.", "setfusion_noaug"),
            (r"\;-- skeleton attention", "setfusion_nojoint"), (r"\;-- temporal conv.", "setfusion_notemporal"),
            (r"\;wider, $d{=}64$", "setfusion_d64"), (r"\;wider, $d{=}128$", "setfusion_d128"),
            ("Hybrid (set gate + raw-coord.\\ residual)", "setres"), ("Residual-only", "resid64"),
            ("v1 design (hidden 64)", "tripose64"), ("v1 design (hidden 128, original)", "tripose128")]
    data = []
    for label, tag in rows:
        rs = folds(f"eqb_{tag}")
        m = MM * np.mean([r["learned_last"]["mpjpe_m"] for r in rs])
        p = MM * np.mean([r["learned_last"]["pa_mpjpe_m"] for r in rs])
        data.append((label, rs[0]["params"], m, p, stress(f"eqb_{tag}", "zero", True)[0], stress(f"eqb_{tag}", "noise", True)[0]))
    b = [bold([d[k] for d in data], ".1f") for k in (2, 3, 4, 5)]
    lines = [f"{d[0]} & {params(d[1])} & {b[0][i]} & {b[1][i]} & {b[2][i]} & {b[3][i]} \\\\" for i, d in enumerate(data)]
    write("tab_ablation", lines)


def tab_budget() -> None:
    def curve(tag):
        by = {}
        for r in folds(tag):
            for h in r["history"]:
                by.setdefault(h["step"], []).append((h["mpjpe_m"], h["pa_mpjpe_m"]))
        return {s: MM * np.mean(v, axis=0) for s, v in by.items() if len(v) == 5}
    ours, res = curve("eqb24k_setfusion"), curve("eqb24k_resid64")
    steps = (2000, 4000, 6000, 12000, 24000)
    final = lambda tag: (lambda rs: (MM * np.mean([r["learned_last"]["mpjpe_m"] for r in rs]), MM * np.mean([r["learned_last"]["pa_mpjpe_m"] for r in rs])))(folds(tag))
    wins = (16, 32, 64, 128, 256)
    wtag = lambda w, name: f"eqb_{name}" if w == 64 else f"eqbw{w}_{name}"
    c = lambda x: f"{x[0]:.1f}/{x[1]:.1f}"
    lines = [r"\multicolumn{6}{c}{\emph{Training steps (32 $\times$ 64-frame windows per step)}}\\",
             " & " + " & ".join(f"{s // 1000}K" for s in steps) + r" \\", r"\midrule",
             r"\method{} & " + " & ".join(c(ours[s]) for s in steps) + r" \\",
             "Residual-only & " + " & ".join(c(res[s]) for s in steps) + r" \\", r"\midrule",
             r"\multicolumn{6}{c}{\emph{Window length in frames (2{,}048 frames per step, 6K steps)}}\\",
             " & " + " & ".join(str(w) for w in wins) + r" \\", r"\midrule",
             r"\method{} & " + " & ".join(c(final(wtag(w, "setfusion"))) for w in wins) + r" \\",
             "Residual-only & " + " & ".join(c(final(wtag(w, "resid64"))) for w in wins) + r" \\",
             "Temporal-CNN & " + " & ".join(c(final(wtag(w, "tcn"))) for w in wins) + r" \\"]
    write("tab_budget", lines)


TABLES = {"main": tab_main, "groups": tab_groups, "stress": tab_stress, "da": tab_da, "downstream": tab_downstream,
          "ablation": tab_ablation, "budget": tab_budget}

if __name__ == "__main__":
    for name in (sys.argv[1:] or list(TABLES)):
        TABLES[name]()
